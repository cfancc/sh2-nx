"""Compare the native C font driver's output with Pillow and independent glyph averages."""
import argparse
import json
from pathlib import Path
from PIL import Image


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[2])
    root = parser.parse_args().root.resolve(strict=True)
    build = root / 'build'
    source = root / 'game/lang/font/font000.tga'
    with Image.open(source) as image:
        rgba = image.convert('RGBA')
    actual = (build / 'font-decoded.bgra').read_bytes()
    assert actual == rgba.tobytes('raw', 'BGRA'), 'C TGA decoder differs from Pillow'
    del actual
    pixels = rgba.load()
    columns = rgba.width // 44
    cases = [(0, 0), (1, 33), (24, 350), (25, 7000), (424, 0x2000 | 7000), (100, 0x2000 | 7499)]
    for index, (_, code) in enumerate(cases):
        glyph = code & 0x1FFF
        sx = glyph % columns * 44
        sy = glyph // columns * 64 + (rgba.height // 2 if code & 0x2000 else 0)
        expected = bytearray()
        for y in range(32):
            for x in range(22):
                samples = [pixels[sx + x * 2 + dx, sy + y * 2 + dy] for dy in (0, 1) for dx in (0, 1)]
                expected.extend(sum(sample[c] for sample in samples) // 4 for c in (2, 1, 0, 3))
        assert (build / f'glyph-{index}.bgra').read_bytes() == expected, f'Glyph {index} mismatch'
    report = {'decoder_matches_pillow': True, 'pixels_checked': rgba.width * rgba.height,
              'independent_glyph_checks': len(cases)}
    (build / 'zh-font-check.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
    # Remove only the seven scratch outputs generated by the native font driver.
    for name in ['font-decoded.bgra'] + [f'glyph-{i}.bgra' for i in range(len(cases))]:
        (build / name).unlink()
    print(json.dumps(report))


if __name__ == '__main__':
    main()
